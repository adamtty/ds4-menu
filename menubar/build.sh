#!/bin/bash
# Compile the menu bar app with ds4proxy.py embedded in the binary, so the code it runs with its
# ~/Documents permission is covered by the app's signature instead of read from a writable file.
# The ds4 checkout's path is baked in too, rather than read from the (user-writable) LaunchAgent.
# Usage: [DS4_DIR=/path/to/ds4] menubar/build.sh OUTPUT_BINARY
set -eu
DS4_DIR=${DS4_DIR:-$HOME/Documents/code-work/ds4}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=$1
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# one main.swift: the embedded source has to come first, since top-level code after app.run()
# never executes
{
  printf '// generated by menubar/build.sh from ds4proxy.py; do not edit\n'
  printf 'let proxySourceBase64 = "%s"\n' "$(base64 < "$ROOT/ds4proxy.py" | tr -d '\n')"
  printf 'let ds4DirBase64 = "%s"\n\n' "$(printf %s "$DS4_DIR" | base64 | tr -d '\n')"
  cat "$ROOT/menubar/DS4Menu.swift"
} > "$WORK/main.swift"

swiftc -O -target arm64-apple-macos13 -framework AppKit -o "$OUT" "$WORK/main.swift"
